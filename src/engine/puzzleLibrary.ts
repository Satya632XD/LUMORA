function parseStringGrid(str: string): number[][] {
  const grid: number[][] = [];
  for (let r = 0; r < 9; r++) {
    const row: number[] = [];
    for (let c = 0; c < 9; c++) {
      const ch = str[r * 9 + c] || '0';
      const num = parseInt(ch, 10);
      row.push(isNaN(num) ? 0 : num);
    }
    grid.push(row);
  }
  return grid;
}

export function getCuratedPuzzle(difficulty: Difficulty): PuzzleDefinition | null {
  const seeds = FALLBACK_SEEDS[difficulty] || FALLBACK_SEEDS.medium;
  const picked = seeds[Math.floor(Math.random() * seeds.length)];
  const puzzle = parseStringGrid(picked);
  
  const { solved, solution } = solveSudoku(puzzle);
  if (!solved || !solution) return null;

  let cluesCount = 0;
  for (let r = 0; r < 9; r++) {
    for (let c = 0; c < 9; c++) {
      if (puzzle[r][c] !== 0) cluesCount++;
    }
  }

  return {
    id: `curated_${difficulty}_${Date.now()}_${Math.random().toString(36).substring(2, 6)}`,
    puzzle,
    solution,
    difficulty,
    cluesCount,
  };
}
